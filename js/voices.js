// 設定パネルのボイス読み上げON/OFF(OFFでもセリフ文字列は返す=吹き出しは出る)
let voicesEnabled = true;
export function setVoicesEnabled(flag) {
  voicesEnabled = !!flag;
  if (!voicesEnabled && "speechSynthesis" in window) speechSynthesis.cancel();
}

let jaVoice = null;
function loadVoices() {
  if (!("speechSynthesis" in window)) return;
  const pick = () => {
    const vs = speechSynthesis.getVoices();
    jaVoice = vs.find((v) => v.localService === true && v.lang && v.lang.startsWith("ja")) || null;
  };
  pick();
  if (!jaVoice) speechSynthesis.addEventListener("voiceschanged", pick, { once: true });
}
loadVoices();

// 叩かれたときに呼ぶ。毎回ではなくランダム(約35%)で発声する。
export function maybeSlapVoice(costumeId, progress = 0) {
  if (!("speechSynthesis" in window)) return null;
  if (Math.random() > 0.35) return null;
  if (speechSynthesis.speaking) return null; // 重ねない
  const set = VOICE_SETS[costumeId] || VOICE_SETS.suit;
  const line = set.lines[Math.floor(Math.random() * set.lines.length)];
  if (!voicesEnabled || !jaVoice) return line; // 読み上げOFFでも吹き出しは出す
  const u = new SpeechSynthesisUtterance(line);
  if (jaVoice) u.voice = jaVoice;
  u.lang = "ja-JP";
  // 進行が進むほど声が上ずる
  u.pitch = Math.min(2, set.pitch + progress * 0.3);
  u.rate = set.rate + progress * 0.2;
  u.volume = 0.9;
  speechSynthesis.speak(u);
  return line;
}

// エンディングの叫び。衣装別のラインからランダムに選び、叫んだセリフを返す。
export function screamVoice(costumeId) {
  const lines = SCREAM_LINES[costumeId] || SCREAM_LINES.suit;
  const line = lines[Math.floor(Math.random() * lines.length)];
  if (!("speechSynthesis" in window) || !voicesEnabled || !jaVoice) return line;
  speechSynthesis.cancel();
  const u = new SpeechSynthesisUtterance(line);
  if (jaVoice) u.voice = jaVoice;
  u.lang = "ja-JP";
  const set = VOICE_SETS[costumeId] || VOICE_SETS.suit;
  u.pitch = Math.min(2, set.pitch + 0.3);
  u.rate = 1.2;
  u.volume = 1;
  speechSynthesis.speak(u);
  return line;
}
